// Пример работы новой логики расчета шанса апгрейда

class ChanceCalculator {
  private calculateChanceByPrice(
    usedPrice: number,
    targetPrice: number,
  ): number {
    // Шанс зависит от соотношения цены используемого ресурса к целевому скину
    // Если цена используемого ресурса больше или равна целевому скину - высокий шанс
    // Если цена используемого ресурса меньше целевого скина - шанс пропорционально уменьшается
    
    const priceRatio = usedPrice / targetPrice

    if (priceRatio >= 1.0) {
      // Если тратим больше или равно цене целевого скина - 85% шанс
      return 85
    } else if (priceRatio >= 0.8) {
      // 80-100% от цены целевого скина - 70% шанс
      return 70
    } else if (priceRatio >= 0.6) {
      // 60-80% от цены целевого скина - 55% шанс
      return 55
    } else if (priceRatio >= 0.4) {
      // 40-60% от цены целевого скина - 40% шанс
      return 40
    } else if (priceRatio >= 0.2) {
      // 20-40% от цены целевого скина - 25% шанс
      return 25
    } else {
      // Меньше 20% от цены целевого скина - 10% шанс
      return 10
    }
  }

  demonstrateLogic() {
    console.log('=== Примеры расчета шанса апгрейда ===\n')
    
    const examples = [
      // [используемая цена, целевая цена, описание]
      [1000, 1000, 'Равные цены (скин за 1000 -> скин за 1000)'],
      [1200, 1000, 'Переплата (скин за 1200 -> скин за 1000)'],
      [800, 1000, '80% от цены (скин за 800 -> скин за 1000)'],
      [600, 1000, '60% от цены (скин за 600 -> скин за 1000)'],
      [400, 1000, '40% от цены (скин за 400 -> скин за 1000)'],
      [200, 1000, '20% от цены (скин за 200 -> скин за 1000)'],
      [100, 1000, '10% от цены (скин за 100 -> скин за 1000)'],
      
      // Примеры с денежным апгрейдом
      [500, 500, 'Баланс: потратить 500 на скин за 500'],
      [750, 1000, 'Баланс: потратить 750 на скин за 1000'],
      [300, 1000, 'Баланс: потратить 300 на скин за 1000'],
    ]

    examples.forEach(([usedPrice, targetPrice, description]) => {
      const chance = this.calculateChanceByPrice(usedPrice, targetPrice)
      const ratio = ((usedPrice / targetPrice) * 100).toFixed(1)
      
      console.log(`${description}`)
      console.log(`  Соотношение: ${ratio}% (${usedPrice}/${targetPrice})`)
      console.log(`  Шанс успеха: ${chance}%`)
      console.log('')
    })

    console.log('=== Выводы ===')
    console.log('• Теперь шанс честно зависит от вложенных средств')
    console.log('• Чем больше тратишь относительно цены целевого скина, тем выше шанс')
    console.log('• Система стимулирует пользователей вкладывать больше для получения лучших шансов')
    console.log('• Минимальный шанс 10% даже при небольших вложениях')
    console.log('• Максимальный шанс 85% при переплате или равной стоимости')
  }
}

// Запуск примера
const calculator = new ChanceCalculator()
calculator.demonstrateLogic()
